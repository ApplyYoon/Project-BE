-- 이미 테이블이 있는 Neon DB 에 "숨긴 사용설명서 항목"(이슈 #46) 표를 더하는 SQL 입니다.
--
-- 무엇이 바뀌나요?
--   manual_hidden_items : 한 사람이 숨긴 사용설명서 항목마다 한 줄 (누가 · 어느 항목 이름표)
--   같은 사람이 같은 항목을 두 번 숨겨도 한 줄만 남습니다. (user_id + item_id 중복 금지)
--
-- 누가 · 언제 실행하나요?
--   이 표는 다른 기존 표를 가리키지 않아서, 앞 번호를 어디까지 실행했든 그대로 실행해도 됩니다.
--   Neon 콘솔 → 브랜치 고르기 → SQL Editor 에 이 파일 전체를 붙여 넣고 Run.
--   dev 브랜치는 지금 바로, main 브랜치는 이 PR 이 들어간 develop → main 배포 **전에** 실행합니다.
--   (이 표가 없으면 /api/v1/manual 이 500 이고, 탈퇴도 500 입니다. 탈퇴는 userId 가 있는 모든 테이블에서 그 사람의 줄을 지움)
--
-- 여러 번 실행해도 되나요?
--   네. "없으면 만들기(if not exists)" 뿐이고, 줄(데이터)은 지우지 않습니다. (MigrationSqlTest 가 검사)
--   begin ~ commit 으로 묶여 있어서, 중간에 에러가 나면 하나도 바뀌지 않습니다.

begin;

create table if not exists manual_hidden_items (
    id bigint generated by default as identity,
    user_id bigint not null,
    item_id varchar(100) not null,
    primary key (id),
    constraint uk_manual_hidden_items_user_id_item_id unique (user_id, item_id)
);

commit;
