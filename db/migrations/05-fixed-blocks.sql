-- 고정 일정 (#223)
--   없으면 고정 일정 API(/api/v1/fixed-blocks)가 500 이고, 탈퇴도 500 입니다.
--   (탈퇴는 userId 가 있는 모든 테이블에서 그 사람의 줄을 지우는데, 테이블이 없으면 거기서 멈춥니다)
create table if not exists fixed_blocks (
    end_time time(0) not null,
    start_time time(0) not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    repeat_days varchar(20) not null,
    title varchar(20) not null,
    primary key (id)
);
create index if not exists idx_fixed_blocks_user_id on fixed_blocks (user_id);

commit;
