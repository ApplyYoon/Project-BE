begin;

create table if not exists calendar_alarms (
    handled_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    starts_at timestamp(6) with time zone not null,
    user_id bigint not null,
    event_key varchar(255) not null,
    title varchar(100) not null,
    primary key (id),
    constraint uk_calendar_alarms_user_id_event_key unique (user_id, event_key)
);

create index if not exists idx_calendar_alarms_starts_at
   on calendar_alarms (starts_at);

commit;
