begin;

-- 한 줄 = 한 사람의 하루 관리 단계(0 ~ 4)와 그 이유
create table if not exists daily_care_stages (
    stage integer not null,
    stage_date date not null,
    suggest_shrink boolean not null,
    decided_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    rule varchar(20) not null check ((rule in ('SAFETY','RECOVERY','UP','HOLD_UNAVOIDABLE','HOLD_OVERLOAD','HOLD_UNKNOWN','TO_BASE'))),
    reason varchar(200) not null,
    primary key (id),
    constraint uk_daily_care_stages_user_id_stage_date unique (user_id, stage_date)
);

commit;
