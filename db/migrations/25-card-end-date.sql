-- 이미 테이블이 있는 Neon DB 에 "반복 카드를 그만하는 날"(cards.end_date) 칸을 더하는 SQL 입니다. (2026-10-25 QA)
--
-- 왜?
--   반복 카드에는 끝나는 날이 없어서, 연결한 목표를 그만두거나 D-day 가 지나도 루틴 카드가 계속 생겼습니다.
--   (홈 · 카드 탭에 계속 보이고, 알림도 오고, 관리 단계 판정은 그 카드를 "안 한 카드" 로 셉니다)
--   이 칸에 날짜가 있으면 그 날까지만 반복합니다. 목표가 끝나면 FE 가 채웁니다.
--   비어 있으면 지금처럼 끝 없이 반복합니다. 이미 있는 카드는 모두 비어 있는(null) 채로 시작합니다.
--
-- 누가 · 언제 실행하나요?
--   cards 표가 있는 Neon 브랜치(04 를 실행한 곳)에 실행합니다. 다른 번호와는 상관없어서 순서가 바뀌어도 됩니다.
--   (23 · 24 번은 다른 PR(#444)이 쓰고 있어서 25 번입니다)
--   Neon 콘솔 → 브랜치 고르기 → SQL Editor 에 이 파일 전체를 붙여 넣고 Run.
--   dev 브랜치는 지금 바로, main 브랜치는 이 칸이 들어간 develop → main 배포 **전에** 실행합니다.
--   (이 칸이 없으면 카드 API 와 카드를 읽는 모든 기능, 탈퇴가 500 입니다)
--
-- 여러 번 실행해도 되나요?
--   네. 칸은 "없으면 더하기(if not exists)" 라서 다시 실행해도 에러가 나지 않습니다. (MigrationSqlTest 가 검사)
--   지우는 데이터는 없습니다.

begin;

alter table cards add column if not exists end_date date;

commit;
