-- 이미 테이블이 있는 Neon DB 에 "변형 문제" 기능(docs/VARIANT-SPEC.md)의 테이블을 더하는 SQL 입니다.
--
-- 누가 · 언제 실행하나요?
--   새 테이블들은 다른 표를 가리키지 않아서(번호만 적음), 01 ~ 21 을 어디까지 실행했든 그대로 실행해도 됩니다.
--   Neon 콘솔 → 브랜치 고르기 → SQL Editor 에 이 파일 전체를 붙여 넣고 Run.
--   dev 브랜치에서 먼저 실행해 서버가 켜지는 것을 확인하고, main 브랜치는 이 PR 이 develop → main 으로 배포되기 **전에** 실행합니다.
--   (이 표들이 없으면 /api/v1/variant/** 와 예약 작업 variant-* 가 500 입니다)
--
-- 여러 번 실행해도 되나요?
--   네. "없으면 만들기(if not exists)" 와 "지우고 다시 만들기(drop ... if exists → add)" 뿐입니다. (MigrationSqlTest 가 검사)
--   begin ~ commit 으로 묶여 있어서, 중간에 에러가 나면 하나도 바뀌지 않습니다.
--
-- 탈퇴하면 이 표들의 그 사람 줄도 지워집니다. (AccountService.withdraw 가 user_id 가 있는 표를 모두 돎)

begin;

-- 1) 원본 문항과 그 선지
create table if not exists source_problems (
    classification_confidence float(53),
    has_figure boolean not null,
    is_correct boolean not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    solved_at timestamp(6) with time zone not null,
    user_id bigint not null,
    classification_source varchar(10) check ((classification_source in ('UPSTREAM','LLM'))),
    type_code varchar(20),
    unit_code varchar(20),
    support_status varchar(30) not null check ((support_status in ('SUPPORTED','PENDING_CLASSIFICATION','NEEDS_REVIEW','UNSUPPORTED_FIGURE'))),
    fingerprint varchar(64) not null,
    correct_answer varchar(200),
    student_answer varchar(200),
    problem_text varchar(2000) not null,
    primary key (id)
);

create table if not exists source_problem_choices (
    position integer not null,
    source_problem_id bigint not null,
    text varchar(200) not null,
    primary key (position, source_problem_id)
);
alter table source_problem_choices drop constraint if exists fk_source_problem_choices_source_problem_id;
alter table source_problem_choices
   add constraint fk_source_problem_choices_source_problem_id
   foreign key (source_problem_id)
   references source_problems (id);

-- 2) 학습 항목 (틀린 원본 하나를 다시 익히는 과정)
create table if not exists review_items (
    current_level integer not null,
    needs_attention boolean not null,
    next_due_date date,
    wrong_streak integer not null,
    created_at timestamp(6) with time zone not null,
    graduated_at timestamp(6) with time zone,
    mastered_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone not null,
    active_source_problem_id bigint,
    id bigint generated by default as identity,
    source_problem_id bigint not null,
    user_id bigint not null,
    status varchar(10) not null check ((status in ('ACTIVE','GRADUATED','MASTERED'))),
    origin varchar(30) not null check ((origin in ('DAILY_WRONG','WEEKLY_CORRECT_FAIL'))),
    primary key (id),
    constraint uk_review_items_active_source_problem_id unique (active_source_problem_id)
);

-- 3) 변형 문항 (생성 시도마다 한 줄)과 그 선지
create table if not exists variants (
    answer_index integer,
    generation_attempt integer not null,
    input_tokens integer,
    level integer not null,
    output_tokens integer,
    short_answer integer,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    source_problem_id bigint not null,
    user_id bigint not null,
    format varchar(10) check ((format in ('MC5','SHORT'))),
    status varchar(10) not null check ((status in ('VERIFIED','REJECTED'))),
    prompt_version varchar(40) not null,
    fingerprint varchar(64) not null,
    model varchar(100) not null,
    rejection_reason varchar(500),
    computed_latex varchar(1000),
    problem_text varchar(2000) not null,
    verification_code varchar(2000) not null,
    solution varchar(4000) not null,
    verification_log varchar(4000) not null,
    primary key (id)
);

create table if not exists variant_choices (
    position integer not null,
    variant_id bigint not null,
    value_expr varchar(200) not null,
    rationale varchar(300) not null,
    latex varchar(1000) not null,
    primary key (position, variant_id)
);
alter table variant_choices drop constraint if exists fk_variant_choices_variant_id;
alter table variant_choices
   add constraint fk_variant_choices_variant_id
   foreign key (variant_id)
   references variants (id);

-- 4) 월간 세트 · 과제 · 답
create table if not exists weekly_sets (
    due_date date not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    week_start date not null,
    primary key (id),
    constraint uk_weekly_sets_user_id_week_start unique (user_id, week_start)
);

create table if not exists assignments (
    assigned_date date not null,
    due_date date not null,
    daily_review_item_id bigint,
    id bigint generated by default as identity,
    weekly_set_id bigint,
    review_item_id bigint,
    source_problem_id bigint not null,
    user_id bigint not null,
    variant_id bigint not null,
    status varchar(10) not null check ((status in ('PENDING','ANSWERED','EXPIRED'))),
    kind varchar(30) not null check ((kind in ('DAILY','WEEKLY_CORRECT_TYPE','WEEKLY_WRONG_DEEP'))),
    primary key (id),
    constraint uk_assignments_variant_id unique (variant_id),
    constraint uk_assignments_daily_review_item_id_assigned_date unique (daily_review_item_id, assigned_date),
    constraint uk_assignments_weekly_set_id_source_problem_id_kind unique (weekly_set_id, source_problem_id, kind)
);

create table if not exists attempts (
    is_correct boolean not null,
    time_spent_sec integer,
    answered_at timestamp(6) with time zone not null,
    assignment_id bigint not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    submitted_answer varchar(20) not null,
    primary key (id),
    constraint uk_attempts_assignment_id unique (assignment_id)
);

-- 5) 찾기 쉽게 만드는 목차(색인)
create index if not exists idx_assignments_user_id_assigned_date
   on assignments (user_id, assigned_date);
create index if not exists idx_assignments_status_due_date
   on assignments (status, due_date);
create index if not exists idx_review_items_user_id_status
   on review_items (user_id, status);
create index if not exists idx_review_items_source_problem_id
   on review_items (source_problem_id);
create index if not exists idx_source_problems_user_id_solved_at
   on source_problems (user_id, solved_at);
create index if not exists idx_variants_source_problem_id_level_status
   on variants (source_problem_id, level, status);

-- 6) GPT 호출 기록 종류에 VARIANT 를 더합니다. (GptUsageKind)
--    PostgreSQL 은 칸에 붙은 검사 규칙에 "테이블_칸_check" 라는 이름을 붙입니다. 그 이름으로 지우고 새 목록으로 다시 만듭니다.
alter table gpt_usages drop constraint if exists gpt_usages_kind_check;
alter table gpt_usages
   add constraint gpt_usages_kind_check
   check (kind in ('CALL','CALL_REVIEW','COACH','PLAN_PARSE','CHAT','CHECKLIST','ASSIST','VARIANT'));

commit;
