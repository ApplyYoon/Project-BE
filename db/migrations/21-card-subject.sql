-- 이미 테이블이 있는 Neon DB 에 "카드의 과목"(cards.subject_id) 칸을 더하는 SQL 입니다. (이슈 #404, 2026-10-24)
--
-- 왜?
--   카드에 과목 칸이 없어서, 카드 타이머로 잰 공부 기록이 과목 없이 저장되고 과목별 시간이 '기타' 로 묶였습니다.
--   카드에 과목을 붙이고, 과목 없이 온 카드 공부 기록에는 카드의 과목을 채웁니다.
--   과목 없는 카드도 있어서 비어 있어도 되는 칸입니다. 이미 있는 카드는 모두 "과목 없음"(null)으로 남습니다.
--
-- 외래 키는 왜 없나요?
--   cards.goal_id · study_sessions.subject_id 처럼 번호만 적습니다. 과목을 지우면 서버(SubjectService)가 이 칸을 비웁니다.
--   (탈퇴는 user_id 가 있는 테이블을 하나씩 지우는데, 외래 키가 있으면 지우는 순서에 따라 실패할 수 있어서)
--
-- 누가 · 언제 실행하나요?
--   cards 표가 있는 Neon 브랜치(04 를 실행한 곳)에 실행합니다. 19 · 20 번과는 상관없어서 순서가 바뀌어도 됩니다.
--   (19 · 20 번은 다른 PR 이 쓰고 있어서 21 번입니다)
--   Neon 콘솔 → 브랜치 고르기 → SQL Editor 에 이 파일 전체를 붙여 넣고 Run.
--   dev 브랜치는 지금 바로, main 브랜치는 이 칸이 들어간 develop → main 배포 **전에** 실행합니다.
--   (이 칸이 없으면 카드 API 와 카드를 읽는 모든 기능, 탈퇴가 500 입니다)
--
-- 여러 번 실행해도 되나요?
--   네. 칸은 "없으면 더하기(if not exists)" 라서 다시 실행해도 에러가 나지 않습니다. (MigrationSqlTest 가 검사)
--   지우는 데이터는 없습니다.

begin;

alter table cards add column if not exists subject_id bigint;

commit;
