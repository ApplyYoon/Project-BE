-- 이미 테이블이 있는 Neon DB 에 "이번 주 목표"(weekly_goals) 표를 만드는 SQL 입니다. (이슈 #88, 2026-10-18)
--
-- 왜?
--   한 주에 하나 정하는 숫자 목표(완주율 · 시작 지연 · 계획 채우기 · 지난주만큼)를 저장하고,
--   주가 끝나면 예약 작업(weekly-goals)이 기록으로 달성 여부를 적어 두려고 합니다.
--
-- 누가 · 언제 실행하나요?
--   10 까지 실행한 Neon 브랜치에 실행합니다. (모르겠으면 01 부터 다시 순서대로 실행해도 됩니다)
--   dev 브랜치는 지금 바로, main 브랜치는 이 표가 들어간 develop → main 배포 **전에** 실행합니다.
--
-- 여러 번 실행해도 되나요?
--   네. 표는 "없으면 만들기(if not exists)" 라서 다시 실행해도 에러가 나지 않습니다. (MigrationSqlTest 가 검사)
--   지우는 데이터는 없습니다.

begin;

create table if not exists weekly_goals (
    baseline integer not null,
    result_value integer,
    target integer not null,
    week_start date not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    judged_at timestamp(6) with time zone,
    user_id bigint not null,
    status varchar(10) check ((status in ('ACHIEVED','MISSED','UNKNOWN'))),
    kind varchar(15) not null check ((kind in ('COMPLETION','START_DELAY','PLAN_RATE','KEEP'))),
    primary key (id),
    constraint uk_weekly_goals_user_id_week_start unique (user_id, week_start)
);

commit;
