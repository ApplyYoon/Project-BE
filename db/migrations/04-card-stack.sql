-- 1) 카드와 카드에 매달린 체크리스트 · 예상 실패 원인 (#254)
create table if not exists cards (
    alert_minutes_before integer,
    card_date date not null,
    duration_minutes integer not null,
    expected_done integer,
    start_time time(0),
    created_at timestamp(6) with time zone not null,
    goal_id bigint,
    id bigint generated by default as identity,
    planning_ms bigint,
    user_id bigint not null,
    alert_method varchar(10) check ((alert_method in ('MESSAGE','CALL'))),
    priority varchar(10) not null check ((priority in ('ABSOLUTE','FLEXIBLE'))),
    type varchar(10) not null check ((type in ('SELF','LECTURE'))),
    repeat_days varchar(20),
    expected_done_reason varchar(30),
    alert_text varchar(100),
    title varchar(100) not null,
    primary key (id)
);
create index if not exists idx_cards_user_id_card_date on cards (user_id, card_date);

create table if not exists card_checklist_items (
    position integer not null check ((position>=0)),
    card_id bigint not null,
    item_key varchar(40) not null,
    text varchar(100) not null,
    primary key (position, card_id)
);
alter table card_checklist_items drop constraint if exists fk_card_checklist_items_card_id;
alter table card_checklist_items
   add constraint fk_card_checklist_items_card_id
   foreign key (card_id)
   references cards (id);

create table if not exists card_expected_fail_causes (
    position integer not null check ((position>=0)),
    card_id bigint not null,
    cause varchar(100) not null,
    primary key (position, card_id)
);
alter table card_expected_fail_causes drop constraint if exists fk_card_expected_fail_causes_card_id;
alter table card_expected_fail_causes
   add constraint fk_card_expected_fail_causes_card_id
   foreign key (card_id)
   references cards (id);

-- 2) 카드 하루치의 미루기 · 실패 표시 (#263)
create table if not exists card_day_marks (
    crisis_detected boolean not null,
    mark_date date not null,
    new_date date,
    new_start_time time(0),
    card_id bigint not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    mark varchar(10) not null check ((mark in ('POSTPONED','FAILED'))),
    cause varchar(20) check ((cause in ('TIRED','EVENT','PHONE','TOO_MUCH','UNWILLING','SICK','PROCRASTINATED','ETC'))),
    reason varchar(500),
    primary key (id),
    constraint uk_card_day_marks_card_id_mark_date unique (card_id, mark_date)
);
create index if not exists idx_card_day_marks_user_id_mark_date on card_day_marks (user_id, mark_date);

-- 3) 휴식 처리한 날 (#263)
create table if not exists rest_days (
    rest_date date not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    primary key (id),
    constraint uk_rest_days_user_id_rest_date unique (user_id, rest_date)
);

