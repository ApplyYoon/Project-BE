--
-- ⚠️ db/migrations 의 파일은 항상 01 부터 끝 번호까지 순서대로 실행합니다. (뒤 파일이 앞 파일의 허용값을 넓히기도 합니다)

begin;

-- 1) 동의 기록 (#204) — 없으면 로그인한 사람의 모든 저장(POST · PUT · PATCH)이 500
create table if not exists consent_records (
    age_confirmed_over14 boolean,
    agreed_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    text_version varchar(20) not null,
    primary key (id)
);
create index if not exists idx_consent_records_user_id_id on consent_records (user_id, id);

-- 1-1) #204 전에 가입한 사람의 동의 기록 채우기
--      이 문장이 없으면 기존 가입자는 모든 저장이 403 CONSENT_REQUIRED 가 됩니다. (FE 에 "다시 동의하기" 화면이 아직 없음)
--      가입 화면은 처음부터 v1 문구에 동의해야 가입되므로, 가입 때 동의한 시각(accounts.agreed_at)으로 채웁니다.
--      만 14세 확인은 그때 서버에 남지 않아서 비워 둡니다. (null = 확인받은 기록 없음)
--      이미 동의 기록이 있는 사람은 건너뜁니다. 그래서 다시 실행해도 두 번 들어가지 않습니다.
insert into consent_records (age_confirmed_over14, agreed_at, user_id, text_version)
select null, a.agreed_at, a.user_id, 'v1'
from accounts a
where a.agreed_at is not null
  and not exists (select 1 from consent_records c where c.user_id = a.user_id);

