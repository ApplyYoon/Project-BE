-- 학교마다의 공개 학사일정이라 개인정보가 없습니다. 탈퇴할 때 지울 줄도 없습니다.

begin;

-- 1) 학교마다 NEIS 에서 마지막으로 받은 때와 교육청 코드
create table if not exists school_event_fetches (
    fetched_at timestamp(6) with time zone not null,
    office_code varchar(10) not null,
    school_code varchar(20) not null,
    primary key (school_code)
);

-- 2) 학사일정 한 줄 = 한 학교의 하루 행사 하나
create table if not exists school_events (
    event_date date not null,
    id bigint generated by default as identity,
    grades varchar(10) not null,
    school_code varchar(20) not null,
    name varchar(100) not null,
    content varchar(200),
    primary key (id),
    constraint uk_school_events_school_code_event_date_name unique (school_code, event_date, name)
);

commit;
