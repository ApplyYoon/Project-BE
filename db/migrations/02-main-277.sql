-- 1) 위험 예측 기록 (#49 · #268)
--    없으면 위험 예측 API(/api/v1/risk-forecasts), 결과를 채우는 예약 작업, 그리고 탈퇴가 500 입니다.
--    (탈퇴는 userId 가 있는 모든 테이블에서 그 사람의 줄을 지우는데, 테이블이 없으면 거기서 멈춥니다)
create table if not exists risk_forecasts (
    actual_achievement_rate integer,
    forecast_date date not null,
    was_correct boolean,
    id bigint generated by default as identity,
    user_id bigint not null,
    risk_level varchar(10) not null check ((risk_level in ('NONE','WATCH','HIGH'))),
    primary key (id),
    constraint uk_risk_forecasts_user_id_forecast_date unique (user_id, forecast_date)
);

create table if not exists risk_forecast_reasons (
    risk_forecast_id bigint not null,
    reason varchar(20) not null check ((reason in ('WEAK_WEEKDAY','LATE_SLEEP'))),
    primary key (risk_forecast_id, reason)
);

alter table risk_forecast_reasons drop constraint if exists fk_risk_forecast_reasons_risk_forecast_id;
alter table risk_forecast_reasons
   add constraint fk_risk_forecast_reasons_risk_forecast_id
   foreign key (risk_forecast_id)
   references risk_forecasts (id);

commit;
