-- 이미 테이블이 있는 Neon DB 에 "일기"(이슈 #60) 표 네 개를 더하는 SQL 입니다.
--
-- 무엇이 생기나요?
--   diaries        : 일기 하나 = 한 줄 (원문은 본인만 봄)
--   diary_emotions : AI 가 뽑은 감정 (체크인 감정 태그와 같은 값)
--   diary_causes   : AI 가 뽑은 실패 원인 (체크인 못 채운 이유와 같은 값)
--   diary_keywords : AI 가 뽑은 반복 키워드
--
-- 누가 · 언제 실행하나요?
--   이 표들은 서로만 가리키고 다른 기존 표를 가리키지 않아서, 앞 번호를 어디까지 실행했든 그대로 실행해도 됩니다.
--   Neon 콘솔 → 브랜치 고르기 → SQL Editor 에 이 파일 전체를 붙여 넣고 Run.
--   dev 브랜치는 지금 바로, main 브랜치는 이 PR 이 들어간 develop → main 배포 **전에** 실행합니다.
--   (이 표가 없으면 /api/v1/diaries 가 500 이고, 탈퇴도 500 입니다. 탈퇴는 userId 가 있는 모든 테이블에서 그 사람의 줄을 지움)
--
-- 여러 번 실행해도 되나요?
--   네. "없으면 만들기(if not exists)" 와 "있으면 지우고 다시 만들기(drop ... if exists → add)" 뿐입니다. (MigrationSqlTest 가 검사)
--   지우는 것은 외래 키 규칙뿐이고, 바로 같은 규칙을 다시 만듭니다. 줄(데이터)은 지우지 않습니다.
--   begin ~ commit 으로 묶여 있어서, 중간에 에러가 나면 하나도 바뀌지 않습니다.

begin;

-- 1) 일기 하나 = 한 줄
create table if not exists diaries (
    diary_date date not null,
    analyzed_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    user_id bigint not null,
    written_at timestamp(6) with time zone not null,
    content varchar(2000) not null,
    primary key (id)
);

create index if not exists idx_diaries_user_id_diary_date
   on diaries (user_id, diary_date);

-- 2) 일기에 딸린 표들 (일기를 지우면 같이 지워짐)
create table if not exists diary_causes (
    diary_id bigint not null,
    cause varchar(20) not null check ((cause in ('TIRED','EVENT','PHONE','TOO_MUCH','UNWILLING','SICK','PROCRASTINATED','ETC'))),
    primary key (diary_id, cause)
);

create table if not exists diary_emotions (
    diary_id bigint not null,
    emotion varchar(20) not null check ((emotion in ('STUCK','ANXIOUS','TIRED','ANNOYED','CALM','MOTIVATED'))),
    primary key (diary_id, emotion)
);

create table if not exists diary_keywords (
    diary_id bigint not null,
    keyword varchar(20) not null,
    primary key (diary_id, keyword)
);

alter table diary_causes drop constraint if exists fk_diary_causes_diary_id;
alter table diary_causes
   add constraint fk_diary_causes_diary_id
   foreign key (diary_id)
   references diaries (id);

alter table diary_emotions drop constraint if exists fk_diary_emotions_diary_id;
alter table diary_emotions
   add constraint fk_diary_emotions_diary_id
   foreign key (diary_id)
   references diaries (id);

alter table diary_keywords drop constraint if exists fk_diary_keywords_diary_id;
alter table diary_keywords
   add constraint fk_diary_keywords_diary_id
   foreign key (diary_id)
   references diaries (id);

commit;
