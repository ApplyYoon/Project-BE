-- 1) 심리검사 한 번 (#219)
--    없으면 심리검사 저장 · 최근 결과 API(/api/v1/psych-tests), 성향 요약 AI(/api/v1/ai/profile-lines),
--    카드 체크리스트 AI 가 500 이고, 탈퇴도 500 입니다. (탈퇴는 userId 가 있는 모든 테이블에서 그 사람의 줄을 지움)
create table if not exists psych_tests (
    id bigint generated by default as identity,
    taken_at timestamp(6) with time zone not null,
    user_id bigint not null,
    primary key (id)
);
create index if not exists idx_psych_tests_user_id_id on psych_tests (user_id, id);

-- 2) 심리검사의 문항별 답 (1 ~ 7)
create table if not exists psych_test_answers (
    answer integer not null,
    psych_test_id bigint not null,
    item varchar(4) not null check ((item in ('S1','S2','S3','S4','S5','A1','A2','A3','A4','A5','P1','P2','P3','P4','P5','R1','R2','R3','R4','R5','F1','F2','F3','F4','F5','E1','E2','E3','E4','E5','C1','C2','C3','C4','C5'))),
    primary key (psych_test_id, item)
);

alter table psych_test_answers drop constraint if exists fk_psych_test_answers_psych_test_id;
alter table psych_test_answers
   add constraint fk_psych_test_answers_psych_test_id
   foreign key (psych_test_id)
   references psych_tests (id);

commit;
