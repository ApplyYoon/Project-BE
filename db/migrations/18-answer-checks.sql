--   answer_check_items : 그 기록 안의 문제 하나 = 한 줄 (AI 의 처음 판정 · 지금 판정 · 학생이 고친 시각)
--
-- 누가 · 언제 실행하나요?
--   이 표들은 다른 표를 가리키는 외래 키가 없어서, 앞 번호를 어디까지 실행했든 그대로 실행해도 됩니다.
