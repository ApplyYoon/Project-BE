--   (이 표가 없으면 /api/v1/answer-checks 가 500 이고, 탈퇴도 500 입니다. 탈퇴는 userId 가 있는 모든 테이블에서 그 사람의 줄을 지움)
--
-- 여러 번 실행해도 되나요?
--   네. "없으면 만들기(if not exists)" 뿐입니다. (MigrationSqlTest 가 검사)
--   지우는 문장은 없습니다. begin ~ commit 으로 묶여 있어서, 중간에 에러가 나면 하나도 바뀌지 않습니다.

begin;

-- 1) 채점 기록 하나 = 한 줄
create table if not exists answer_checks (
    check_date date not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    mode varchar(10) not null check ((mode in ('MARKED','UNMARKED'))),
    subject_text varchar(30),
    primary key (id)
);

create index if not exists idx_answer_checks_user_id_check_date
   on answer_checks (user_id, check_date);

-- 2) 기록 안의 문제 하나 = 한 줄 (answer_check_id 는 번호만 적고 외래 키 제약은 걸지 않습니다)
create table if not exists answer_check_items (
    sort_order integer not null,
    answer_check_id bigint not null,
    edited_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    user_id bigint not null,
    mark_read varchar(1) check ((mark_read in ('O','X'))),
    ai_result varchar(10) not null check ((ai_result in ('CORRECT','WRONG','UNSURE'))),
    result varchar(10) not null check ((result in ('CORRECT','WRONG','UNSURE'))),
    problem_number varchar(20) not null,
    ai_answer varchar(100),
    correct_answer varchar(100),
    my_answer varchar(100),
    primary key (id)
);

create index if not exists idx_answer_check_items_user_id_answer_check_id
   on answer_check_items (user_id, answer_check_id);

commit;
