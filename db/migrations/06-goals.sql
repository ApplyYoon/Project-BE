begin;

-- 1) 목표 (#221)
--    없으면 목표 API(/api/v1/goals)가 500 이고, 탈퇴도 500 입니다.
--    (탈퇴는 userId 가 있는 모든 테이블에서 그 사람의 줄을 지우는데, 테이블이 없으면 거기서 멈춥니다)
create table if not exists goals (
    d_day date not null,
    total_amount integer,
    amount_unit varchar(5),
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    kind varchar(10) not null check ((kind in ('SCORE','COMPLETION'))),
    status varchar(10) not null check ((status in ('ACTIVE','DONE','GIVEN_UP'))),
    current_score varchar(20),
    title varchar(40) not null,
    benefit varchar(100) not null,
    cost varchar(100) not null,
    given_up_reason varchar(100),
    obstacle varchar(100) not null,
    plan varchar(100) not null,
    result varchar(100),
    primary key (id)
);
create index if not exists idx_goals_user_id on goals (user_id);

-- 2) 목표값을 고치기 전의 값 (고칠 때마다 한 줄, 지우지 않음)
create table if not exists goal_target_snapshots (
    d_day date not null,
    position integer not null check ((position>=0)),
    total_amount integer,
    amount_unit varchar(5),
    changed_at timestamp(6) with time zone not null,
    goal_id bigint not null,
    current_score varchar(20),
    title varchar(40) not null,
    reason varchar(100) not null,
    primary key (position, goal_id)
);

alter table goal_target_snapshots drop constraint if exists fk_goal_target_snapshots_goal_id;
alter table goal_target_snapshots
   add constraint fk_goal_target_snapshots_goal_id
   foreign key (goal_id)
   references goals (id);

commit;
