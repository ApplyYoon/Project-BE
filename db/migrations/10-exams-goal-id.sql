--   목표 없이 보는 시험도 있어서 비어 있어도 되는 칸입니다. 이미 있는 시험은 모두 "목표 없음"(null)으로 남습니다.
--
-- 누가 · 언제 실행하나요?
--   09 까지 실행한 Neon 브랜치에 실행합니다. (모르겠으면 01 부터 다시 순서대로 실행해도 됩니다)
--   dev 브랜치는 지금 바로, main 브랜치는 이 칸이 들어간 develop → main 배포 **전에** 실행합니다.
--
-- 여러 번 실행해도 되나요?
--   네. 칸은 "없으면 더하기(if not exists)" 라서 다시 실행해도 에러가 나지 않습니다. (MigrationSqlTest 가 검사)
--   지우는 데이터는 없습니다.

