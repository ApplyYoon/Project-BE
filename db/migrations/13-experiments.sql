--   지우는 것은 외래 키 규칙 하나뿐이고, 바로 같은 규칙을 다시 만듭니다. 줄(데이터)은 지우지 않습니다.
--   begin ~ commit 으로 묶여 있어서, 중간에 에러가 나면 하나도 바뀌지 않습니다.

begin;

-- 1) 실험 하나 = 한 줄
create table if not exists experiments (
    baseline_rate float(53),
    experiment_rate float(53),
    min_gain_pp integer not null,
    start_date date not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    judged_at timestamp(6) with time zone,
    user_id bigint not null,
    cause varchar(20) check ((cause in ('TIRED','EVENT','PHONE','TOO_MUCH','UNWILLING','SICK','PROCRASTINATED','ETC'))),
    status varchar(20) not null check ((status in ('RUNNING','EFFECTIVE','NO_EFFECT','UNCLEAR'))),
    strategy varchar(30) not null check ((strategy in ('PHONE_FLIP','PHONE_BAG','PHONE_ROOM','START_FIRST_LINE','START_COUNTDOWN','START_DESK','PLAN_ONE_LESS','PLAN_SHORTER','PLAN_SPLIT','PROOF_ONE_LINE'))),
    hypothesis varchar(100) not null,
    primary key (id)
);

-- 2) 실험 규칙을 붙인 카드 = 카드마다 한 줄
create table if not exists experiment_cards (
    card_id bigint not null,
    experiment_id bigint not null,
    primary key (card_id, experiment_id)
);

alter table experiment_cards drop constraint if exists fk_experiment_cards_experiment_id;
alter table experiment_cards
   add constraint fk_experiment_cards_experiment_id
   foreign key (experiment_id)
   references experiments (id);

commit;
