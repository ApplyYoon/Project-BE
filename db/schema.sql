-- 운영 DB(Neon, PostgreSQL)의 테이블을 만드는 SQL 입니다. (이슈 #75)
--
-- 왜 이 파일이 있나요?
--   배포 설정(application-prod.yml)과 Neon 설정(application-neon.yml)은 서버가 켜질 때 테이블을 만들지 않습니다.
--   운영 DB 가 코드에 따라 멋대로 바뀌면 데이터가 날아가는 사고가 나기 쉬워서, 테이블은 사람이 이 SQL 로 직접 만듭니다.
--   (로컬 H2 는 지금처럼 엔티티를 보고 자동으로 만들어집니다. ddl-auto: create-drop)
--
-- 언제, 어떻게 실행하나요?
--   새 Neon 브랜치(빈 DB)에 한 번만 실행합니다. Neon 콘솔 → 브랜치 고르기 → SQL Editor 에 이 파일 전체를 붙여 넣고 Run.
--   이미 테이블이 있는 DB 에서 다시 실행하면 "already exists" 에러가 나고 아무것도 바뀌지 않습니다. (지우는 문장은 없습니다)
--   ⚠️ main(배포용) 브랜치에는 dev 브랜치에서 먼저 실행해 서버가 켜지는 것을 확인한 뒤에 실행합니다.
--
-- 엔티티(@Entity)를 고치면 이 파일도 같이 고칩니다.
--   - 새 테이블·컬럼은 이 파일에 추가하고, 이미 만든 Neon DB 에는 바뀐 부분만 alter table 로 따로 실행합니다.
--   - 같이 고쳤는지는 테스트(SchemaSqlTest)가 검사합니다. 엔티티와 이 파일이 다르면 ./gradlew build 가 실패합니다.
--   - 이 파일은 Hibernate 가 PostgreSQL 용으로 만들어 주는 SQL 을 바탕으로 썼습니다. 만드는 방법은 README "운영 DB(Neon)" 에 있습니다.

begin;


create table accounts (
    diary_analysis_agreed boolean not null,
    agreed_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null unique,
    name varchar(20),
    school_code varchar(20),
    google_subject varchar(64) unique,
    email varchar(100) not null unique,
    school_name varchar(100),
    password_hash varchar(200),
    primary key (id)
);

create table call_records (
    call_date date not null,
    crisis_detected boolean not null,
    promise_kept boolean,
    finished_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    started_at timestamp(6) with time zone not null,
    user_id bigint not null,
    miss_reason varchar(20) check ((miss_reason in ('TIRED','EVENT','PHONE','TOO_MUCH','UNWILLING','SICK','ETC'))),
    asked_bias varchar(30) check ((asked_bias in ('PLANNING_FALLACY','FUTURE_SELF','WHAT_THE_HELL','EMOTIONAL_REASONING','EXTERNAL_BLAME','ALL_OR_NOTHING','MORAL_LICENSING','OVERGENERALIZING'))),
    found_bias varchar(30) check ((found_bias in ('PLANNING_FALLACY','FUTURE_SELF','WHAT_THE_HELL','EMOTIONAL_REASONING','EXTERNAL_BLAME','ALL_OR_NOTHING','MORAL_LICENSING','OVERGENERALIZING'))),
    asked_question_key varchar(40),
    promise_if varchar(50),
    promise_then varchar(50),
    found_evidence varchar(100),
    actual_question varchar(200),
    summary varchar(300),
    primary key (id)
);

create table care_settings (
    allow_app_lock boolean not null,
    call_time time(0) not null,
    daily_message_count integer not null,
    max_care_level integer not null,
    max_harshness integer not null,
    pending_effective_date date,
    pending_max_care_level integer,
    quiet_end time(0) not null,
    quiet_start time(0) not null,
    id bigint generated by default as identity,
    user_id bigint not null unique,
    primary key (id),
    constraint ck_care_settings_daily_message_count check (daily_message_count between 0 and 5),
    constraint ck_care_settings_max_harshness check (max_harshness between 1 and 5),
    constraint ck_care_settings_max_care_level check (max_care_level between 0 and 4),
    constraint ck_care_settings_pending_max_care_level check (pending_max_care_level is null or pending_max_care_level between 0 and 4)
);

create table checkin_emotions (
    checkin_id bigint not null,
    emotion varchar(20) not null check ((emotion in ('STUCK','ANXIOUS','TIRED','ANNOYED','CALM','MOTIVATED'))),
    primary key (checkin_id, emotion)
);

create table checkins (
    check_in_date date not null,
    condition integer,
    expected_minutes integer,
    mood integer,
    suggestion_kept boolean,
    id bigint generated by default as identity,
    user_id bigint not null,
    source varchar(10) not null check ((source in ('MANUAL','CALL','QUICK'))),
    miss_reason varchar(20) check ((miss_reason in ('TIRED','EVENT','PHONE','TOO_MUCH','UNWILLING','SICK','ETC'))),
    miss_reason_note varchar(50),
    promise_if varchar(100),
    promise_then varchar(100),
    primary key (id),
    constraint uk_checkins_user_id_check_in_date unique (user_id, check_in_date)
);

create table consent_records (
    age_confirmed_over14 boolean,
    agreed_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    text_version varchar(20) not null,
    primary key (id)
);

create table daily_signals (
    signal_date date not null,
    sleep_minutes integer,
    sns_over_thirty_minutes boolean,
    steps integer,
    id bigint generated by default as identity,
    slept_at timestamp(6) with time zone,
    user_id bigint not null,
    woke_at timestamp(6) with time zone,
    primary key (id),
    constraint uk_daily_signals_user_id_signal_date unique (user_id, signal_date)
);

create table exam_scores (
    actual_score integer,
    expected_score integer not null,
    exam_id bigint not null,
    id bigint generated by default as identity,
    subject_id bigint not null,
    user_id bigint not null,
    primary key (id),
    constraint uk_exam_scores_exam_id_subject_id unique (exam_id, subject_id),
    constraint ck_exam_scores_expected_score_range check (expected_score between 0 and 100),
    constraint ck_exam_scores_actual_score_range check (actual_score is null or actual_score between 0 and 100)
);

create table exams (
    exam_date date not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    type varchar(10) not null check ((type in ('MOCK','SCHOOL','QUIZ','ETC'))),
    name varchar(50) not null,
    primary key (id)
);

create table focus_lock_apps (
    id bigint generated by default as identity,
    user_id bigint not null,
    app_name varchar(30) not null,
    primary key (id),
    constraint uk_focus_lock_apps_user_id_app_name unique (user_id, app_name)
);

create table gpt_usages (
    call_seconds integer,
    cost_won integer,
    call_record_id bigint,
    called_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    kind varchar(20) not null check ((kind in ('CALL','CALL_REVIEW','COACH','PLAN_PARSE'))),
    primary key (id),
    constraint ck_gpt_usages_call_seconds check (call_seconds is null or call_seconds >= 0),
    constraint ck_gpt_usages_cost_won check (cost_won is null or cost_won >= 0)
);

create table initial_plans (
    created_date date not null,
    daily_minutes integer not null,
    days_per_week integer not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    primary key (id),
    constraint uk_initial_plans_user_id unique (user_id)
);

create table login_tokens (
    created_at timestamp(6) with time zone not null,
    expires_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    token_hash varchar(64) not null unique,
    primary key (id)
);

create table messages (
    id bigint generated by default as identity,
    read_at timestamp(6) with time zone,
    sent_at timestamp(6) with time zone not null,
    user_id bigint not null,
    text varchar(500) not null,
    kind varchar(255) not null check ((kind in ('CARROT','NUDGE','STICK','EVENT','RECOVERY','CALL'))),
    primary key (id)
);

create table onboarding_answer_failure_causes (
    onboarding_answer_id bigint not null,
    cause varchar(20) not null check ((cause in ('AFTER_EXAM','WEEKEND','LATE_ACADEMY','PHONE','TOO_MUCH_PLAN'))),
    primary key (onboarding_answer_id, cause)
);

create table onboarding_answer_subject_levels (
    confidence integer not null,
    grade integer,
    score integer,
    onboarding_answer_id bigint not null,
    subject_id bigint not null
);

create table onboarding_answers (
    academy_end_time time(0),
    daily_available_minutes integer not null,
    max_focus_minutes integer,
    school_end_time time(0),
    sleep_time time(0),
    target_exam_date date not null,
    wake_up_time time(0),
    answered_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    chronotype varchar(10) check ((chronotype in ('MORNING','NIGHT'))),
    biggest_distraction varchar(20) check ((biggest_distraction in ('PHONE','SLEEPY','WANDERING_MIND','PEOPLE','NOISE','OTHER'))),
    grade varchar(20) not null check ((grade in ('HIGH_1','HIGH_2','HIGH_3','REPEATER','UNIVERSITY'))),
    study_place varchar(20) check ((study_place in ('HOME','SCHOOL','ACADEMY','LIBRARY','CAFE','OTHER'))),
    target_exam varchar(30) not null,
    target_score varchar(30),
    target_university varchar(30),
    goal_reward varchar(50),
    motivation_reason varchar(50),
    primary key (id)
);

create table push_subscriptions (
    id bigint generated by default as identity,
    subscribed_at timestamp(6) with time zone not null,
    user_id bigint not null,
    auth varchar(100) not null,
    p256dh varchar(200) not null,
    endpoint varchar(500) not null unique,
    primary key (id)
);

create table reviews (
    week_start date,
    exam_id bigint,
    id bigint generated by default as identity,
    saved_at timestamp(6) with time zone not null,
    user_id bigint not null,
    type varchar(10) not null check ((type in ('EXAM','WEEKLY'))),
    answer1 varchar(200) not null,
    answer2 varchar(200) not null,
    answer3 varchar(200) not null,
    primary key (id),
    constraint uk_reviews_user_id_exam_id unique (user_id, exam_id),
    constraint uk_reviews_user_id_week_start unique (user_id, week_start)
);

create table setting_changes (
    changed_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    field varchar(30) not null,
    new_value varchar(1000) not null,
    old_value varchar(1000) not null,
    primary key (id)
);

create table study_plans (
    done boolean not null,
    plan_date date not null,
    start_time time(0),
    target_minutes integer not null,
    id bigint generated by default as identity,
    routine_id bigint,
    subject_id bigint,
    user_id bigint not null,
    kind varchar(10) not null check ((kind in ('STUDY','PLAY'))),
    content varchar(200) not null,
    primary key (id),
    constraint ck_study_plans_study_has_subject check (kind = 'PLAY' or subject_id is not null)
);

create table study_sessions (
    pause_count integer not null,
    target_minutes integer,
    ended_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    paused_ms bigint not null,
    plan_id bigint,
    started_at timestamp(6) with time zone not null,
    subject_id bigint,
    user_id bigint not null,
    kind varchar(10) not null check ((kind in ('STUDY','PLAY'))),
    stop_reason varchar(20) check ((stop_reason in ('TIRED','EVENT','PHONE','TOO_MUCH','UNWILLING','SICK','ETC'))),
    primary key (id),
    constraint ck_study_sessions_study_has_subject check (kind = 'PLAY' or subject_id is not null)
);

create table subjects (
    id bigint generated by default as identity,
    user_id bigint not null,
    color varchar(10) not null check ((color in ('RED','ORANGE','GREEN','BLUE','PURPLE'))),
    name varchar(30) not null,
    primary key (id),
    constraint uk_subjects_user_id_name unique (user_id, name)
);

create table thinking_test_scores (
    average float(53) not null,
    thinking_test_id bigint not null,
    habit varchar(30) not null check ((habit in ('PLANNING_FALLACY','FUTURE_SELF','WHAT_THE_HELL','EMOTIONAL_REASONING','EXTERNAL_BLAME','ALL_OR_NOTHING','MORAL_LICENSING','OVERGENERALIZING'))),
    primary key (thinking_test_id, habit)
);

create table thinking_test_weaknesses (
    thinking_test_id bigint not null,
    weakness varchar(20) not null check ((weakness in ('GAME','PHONE','VIDEO','SLEEP','LAZY','DELAY','FOCUS','FRIENDS','TIRED','MOOD','PLANNING'))),
    primary key (thinking_test_id, weakness)
);

create table thinking_tests (
    test_version integer not null,
    id bigint generated by default as identity,
    taken_at timestamp(6) with time zone not null,
    user_id bigint not null,
    primary key (id)
);

create table users (
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    nickname varchar(50) not null,
    primary key (id)
);

create index idx_call_records_user_id_call_date
   on call_records (user_id, call_date);

create index idx_consent_records_user_id_id
   on consent_records (user_id, id);

create index idx_gpt_usages_user_id_called_at
   on gpt_usages (user_id, called_at);

create index idx_messages_user_id_id
   on messages (user_id, id);

create index idx_onboarding_answers_user_id_answered_at
   on onboarding_answers (user_id, answered_at);

create index idx_push_subscriptions_user_id
   on push_subscriptions (user_id);

create index idx_study_plans_user_id_plan_date
   on study_plans (user_id, plan_date);

create index idx_study_sessions_user_id_started_at
   on study_sessions (user_id, started_at);

create index idx_thinking_tests_user_id_id
   on thinking_tests (user_id, id);

alter table if exists checkin_emotions
   add constraint fk_checkin_emotions_checkin_id
   foreign key (checkin_id)
   references checkins (id);

alter table if exists onboarding_answer_failure_causes
   add constraint fk_onboarding_answer_failure_causes_onboarding_answer_id
   foreign key (onboarding_answer_id)
   references onboarding_answers (id);

alter table if exists onboarding_answer_subject_levels
   add constraint fk_onboarding_answer_subject_levels_onboarding_answer_id
   foreign key (onboarding_answer_id)
   references onboarding_answers (id);

alter table if exists thinking_test_scores
   add constraint fk_thinking_test_scores_thinking_test_id
   foreign key (thinking_test_id)
   references thinking_tests (id);

alter table if exists thinking_test_weaknesses
   add constraint fk_thinking_test_weaknesses_thinking_test_id
   foreign key (thinking_test_id)
   references thinking_tests (id);

commit;
