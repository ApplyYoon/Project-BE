// AI 통화는 이 목록에서 오늘 확인할 생각 습관을 하나 골라, 정해 둔 질문으로 학생이 스스로 알아차리게 돕습니다.
//
// ■ 왜 목록으로 정해 두나요?
//   AI 가 질문을 매번 새로 지어내면 날마다 들쭉날쭉하고, 어떤 질문이 도움이 됐는지 나중에 비교할 수 없습니다.
//   그래서 "무엇을 물을지" 는 코드가 정하고, AI 는 그 질문을 자연스럽게 말하기만 합니다. (기획서 v2 3장)
//
// ■ 이름은 "생각" 에 붙이고, "사람" 에게 붙이지 않습니다
//   "그런 생각을 '계획 오류' 라고 해" (O)   "너는 계획 오류형이야" (X)
//   한 번의 실수를 사람의 성격으로 굳히는 말은, 그 자체가 이 목록의 "한 번으로 단정하기" 입니다.
//
// 항목마다 적어 둔 것
//   label        학생에게 보여 주는 이름
//   description  어떤 생각인지 한 줄 (속마음 예시 포함)
//   signalWords  통화 중 학생 말에 이 말이 나오면 이 생각 습관을 의심해 봅니다
//   questions    알아차리게 돕는 질문들. 같은 질문이 연달아 나오지 않게 돌아가며 씁니다. (BiasQuestion)
//   solution     알아차린 뒤 해 볼 행동 하나
//
// 목록을 고칠 때는 CognitiveBiasTest 를 같이 돌려 주세요. 질문·행동에 깎아내리는 말이 섞이면 실패합니다.
