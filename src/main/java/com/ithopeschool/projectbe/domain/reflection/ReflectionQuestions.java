package com.ithopeschool.projectbe.domain.reflection;

import com.ithopeschool.projectbe.domain.care.MissReason;
import java.util.List;

// 성찰일기 질문 세트입니다. (이슈 #61, 기획서 v2 2장 「선택 수집: 일기와 성찰일기」)
// "AI 가 지어내지 않는다" 는 규칙대로, 질문은 여기에 미리 적어 둔 문장만 씁니다.
// 계획을 못 채운 이유마다 세트가 하나씩 있고, 세트마다 질문은 3개입니다. 처방 기간 동안 매일 같은 질문에 답합니다.
//
// 질문을 쓸 때 지킨 것
//   - "왜 못 했어?" 처럼 탓하는 말 대신, 그때 무슨 일이 있었는지와 다음에 할 작은 행동을 묻습니다.
//   - 세 번째 질문은 늘 "해낸 것" 이나 "괜찮았던 때" 를 묻습니다. 못 한 것만 돌아보다 지치지 않게 하려는 것입니다.
//   - 한두 줄로 답할 수 있게 짧게 씁니다. (테이블의 질문 칸은 100자까지)
//
// 아픔(SICK)은 세트가 없습니다. 아플 때는 돌아보기보다 쉬는 것이 먼저라서 처방하지 않습니다. (ReflectionRule)
// 문장을 고치면 앞으로 내릴 처방부터 바뀝니다. 이미 내린 처방은 질문 글을 따로 저장해 두어서 그대로입니다.
public final class ReflectionQuestions {

  // 세트마다 질문 수
  public static final int COUNT = 3;

  // 값만 돌려주는 도구라서 객체를 만들 일이 없습니다.
  private ReflectionQuestions() {}

  // 그 이유의 질문 3개를 돌려줍니다. 세트가 없는 이유(아픔)는 빈 목록입니다.
  public static List<String> of(MissReason reason) {
    return switch (reason) {
      case TIRED ->
          List.of(
              "오늘 가장 피곤했던 때는 언제였어?",
              "내일 조금 더 일찍 자려면 무엇 하나를 바꿀 수 있을까?",
              "오늘 컨디션이 그나마 괜찮았던 시간은 언제였어?");
      case EVENT ->
          List.of(
              "오늘 계획에 없던 일정이 있었어? 미리 알 수 있었던 일이었어?",
              "다음에 일정이 생기면 공부를 언제로 옮길 수 있을까?",
              "바쁜 날에도 해낸 공부가 있었다면 무엇이었어?");
      case PHONE ->
          List.of(
              "오늘 폰을 집어 든 순간, 바로 전에 무엇을 하고 있었어?",
              "내일 그 순간이 오면 폰 대신 무엇을 할까?",
              "오늘 폰 없이 집중한 때가 있었다면 언제였어?");
      case TOO_MUCH ->
          List.of("오늘 계획 중에 생각보다 오래 걸린 것은 무엇이었어?", "내일 계획에서 하나를 뺀다면 무엇을 뺄까?", "오늘 끝낸 것 하나는 무엇이었어?");
      case UNWILLING ->
          List.of(
              "오늘 가장 시작하기 싫었던 공부는 무엇이었어? 무엇이 제일 부담됐어?",
              "내일 그 공부를 딱 5분만 한다면 무엇부터 할까?",
              "오늘 조금이라도 해낸 것 하나는 무엇이었어?");
      // '미루다 보니' 는 #225 에서 더한 이유입니다. 미룬 순간과 다음에 바로 시작할 작은 행동을 묻습니다.
      case PROCRASTINATED ->
          List.of(
              "오늘 공부를 미루게 된 순간, 그 대신 무엇을 하고 있었어?",
              "내일 시작 시각에 책 한 권만 펴 둔다면 무엇을 펼까?",
              "오늘 미루지 않고 바로 시작한 일이 있었다면 무엇이었어?");
      case ETC ->
          List.of("오늘 계획대로 안 된 순간에 무슨 일이 있었어?", "내일 하나만 바꾼다면 무엇을 바꿀까?", "오늘 잘한 한 가지는 무엇이었어?");
      case SICK -> List.of();
    };
  }
}
